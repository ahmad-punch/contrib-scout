import { describe, expect, it } from "vitest";
import {
  analyzePolicyFiles,
  classifyAiStance,
  detectGates,
  extractSentences,
} from "../src/checks/ai-policy.ts";

const file = (text: string, path = "CONTRIBUTING.md") => ({ path, text });

describe("extractSentences", () => {
  it("drops code blocks and link targets and splits sentences", () => {
    const md = "# Title\n\nRead [the docs](https://x.y). Then run it.\n\n```sh\nAI ban\n```\n";
    expect(extractSentences(md)).toEqual(["Title", "Read the docs.", "Then run it."]);
  });
});

describe("classifyAiStance", () => {
  it("returns unknown when no policy files exist", () => {
    expect(classifyAiStance([]).stance).toBe("unknown");
  });

  it("detects a ban with evidence", () => {
    const result = classifyAiStance([
      file("## AI\n\nPull requests generated by AI tools will be rejected.", "AI_POLICY.md"),
    ]);
    expect(result.stance).toBe("ban");
    expect(result.evidence[0]).toEqual({
      file: "AI_POLICY.md",
      text: "Pull requests generated by AI tools will be rejected.",
    });
  });

  it("does not mistake a negated ban for a ban", () => {
    const result = classifyAiStance([file("Using AI tools is not forbidden here.")]);
    expect(result.stance).toBe("neutral");
  });

  it("detects required disclosure", () => {
    const result = classifyAiStance([
      file("If you used an LLM, you must disclose it in the PR description."),
    ]);
    expect(result.stance).toBe("disclose-required");
  });

  it("detects encouraged disclosure", () => {
    const result = classifyAiStance([
      file("We encourage you to disclose any AI assistance you used.", "AGENTS.md"),
    ]);
    expect(result.stance).toBe("disclose-encouraged");
  });

  it("is neutral when AI is mentioned without rules", () => {
    expect(classifyAiStance([file("You may use AI to contribute.")]).stance).toBe("neutral");
  });

  it("ignores words that merely contain the letters ai", () => {
    expect(classifyAiStance([file("The maintainer said it will be rejected.")]).evidence).toEqual(
      [],
    );
  });
});

describe("detectGates", () => {
  it("finds assignment, prior approval and vouch gates", () => {
    const gates = detectGates([
      file(
        "You must be assigned to an issue before opening a PR.\n\nLarge changes need prior approval.\n\nNew contributors need a maintainer to vouch for them.",
      ),
    ]);
    expect(gates.map((g) => g.kind)).toEqual(["assignment", "prior-approval", "vouch"]);
    expect(gates[0]?.evidence.file).toBe("CONTRIBUTING.md");
  });

  it("finds nothing in a permissive guide", () => {
    expect(detectGates([file("Fork the repo, make a change and open a PR.")])).toEqual([]);
  });
});

describe("analyzePolicyFiles", () => {
  it("lists the files that were read", () => {
    const result = analyzePolicyFiles([
      file("Hi."),
      file("Hello.", ".github/PULL_REQUEST_TEMPLATE.md"),
    ]);
    expect(result.filesFound).toEqual(["CONTRIBUTING.md", ".github/PULL_REQUEST_TEMPLATE.md"]);
  });
});
